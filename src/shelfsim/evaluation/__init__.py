"""make backtest: rolling-origin scores for every model, written to outputs/<client>/."""

import polars as pl

from shelfsim.config import ClientConfig, ModelingConfig
from shelfsim.demand import load_panel
from shelfsim.evaluation.backtest import run_folds, summarize
from shelfsim.io import OUTPUTS_DIR, output_dir

ORDER = [
    "M0 naive",
    "M1 log-log",
    "M2 cross-price",
    "M3 hierarchical",
    "M4 LightGBM",
    "Nested logit",
]
START, END = "<!-- results:start -->", "<!-- results:end -->"


def _pct(value) -> str:
    return "n/a" if value is None or value != value else f"{100 * value:.1f}%"


def markdown_table(summary: pl.DataFrame, client_label: str) -> str:
    def get(model, segment, column):
        row = summary.filter((pl.col("model") == model) & (pl.col("segment") == segment))
        return row[column][0] if row.height and column in row.columns else None

    lines = [
        "| Model | Client | WAPE all | WAPE promo | WAPE chain-week | Bias | MASE | Direction accuracy | Promo-lift calibration | Elasticity sd across folds | Plausibility |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for model in ORDER:
        sd = get(model, "all", "elasticity_sd")
        # M0 is flat and promo-blind by construction, so these two don't apply to it.
        direction = "n/a" if model == "M0 naive" else _pct(get(model, "all", "direction_accuracy"))
        lift = get(model, "promo", "promo_lift_calibration")
        lift = "n/a" if model == "M0 naive" or lift is None else f"{lift:.2f}"
        lines.append(
            f"| {model} | {client_label} | {_pct(get(model, 'all', 'wape'))} | {_pct(get(model, 'promo', 'wape'))} | {_pct(get(model, 'all', 'wape_chain_week'))} "
            f"| {_pct(get(model, 'all', 'bias'))} | {get(model, 'all', 'mase'):.2f} | {direction} | {lift} "
            f"| {'n/a' if sd is None else f'{sd:.2f}'} | {_pct(get(model, 'all', 'plausibility'))} |"
        )
    return "\n".join(lines)


def run(cfg: ClientConfig, mcfg: ModelingConfig) -> None:
    panel = load_panel(cfg.client_id, mcfg)
    predictions, elasticities = run_folds(panel, mcfg)
    per_fold, summary = summarize(predictions, elasticities, mcfg)
    out = output_dir(cfg.client_id)
    per_fold.write_csv(out / "backtest.csv")
    summary.write_csv(out / "backtest_summary.csv")
    elasticities.write_csv(out / "backtest_elasticities.csv")
    weeks = predictions["week_start"]
    b = mcfg.backtest
    header = (
        f"Rolling-origin backtest, {cfg.display_name}: {b.n_folds} folds of {b.horizon_weeks} weeks, "
        f"held-out weeks starting {weeks.min()} to {weeks.max()}. Units are store x product x week units."
    )
    (out / "backtest.md").write_text(f"{header}\n\n{markdown_table(summary, cfg.client_id)}\n")
    _update_comparison()


def _update_comparison() -> None:
    """outputs/model_comparison.md: generated tables between markers, your findings below them."""
    path = OUTPUTS_DIR / "model_comparison.md"
    tables = []
    for client_dir in sorted(OUTPUTS_DIR.iterdir()):
        table = client_dir / "backtest.md"
        if table.exists():
            tables.append(table.read_text())
    block = f"{START}\n" + "\n\n".join(tables) + f"\n{END}"
    if path.exists() and START in path.read_text():
        text = path.read_text()
        text = text[: text.index(START)] + block + text[text.index(END) + len(END) :]
    else:
        text = (
            "# Model comparison\n\n"
            "Generated by `make backtest`. Definitions: WAPE = sum |actual - forecast| / sum actual over store x product x week rows; WAPE chain-week = the same on chain-wide weekly category units; bias = sum (forecast - actual) / sum actual; "
            "MASE = absolute error relative to M0 on the same rows; direction accuracy = share of week-on-week price changes of 2% or more where the "
            "forecast moved units the same way as the actuals; promo-lift calibration = predicted / actual incremental units in promo weeks vs M0; "
            "elasticity sd = median over products of the sd of the own-price elasticity across folds; plausibility = share of product-fold "
            "elasticities between the configured bounds.\n\n"
            f"{block}\n\n## Findings\n\nTODO (yours): three findings, including one that surprised you.\n"
        )
    path.write_text(text)
